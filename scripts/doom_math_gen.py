#!/usr/bin/env python3
"""Generate unrolled DW8051-aware 16.16 arithmetic; test with doom_sim.py.

DW8051 costs: register arithmetic/MOV 1 cycle, direct arithmetic 2, MUL/DIV 5,
DJNZ Rn 3, DJNZ direct 4, taken/untaken conditional jump 3 (model JSON).
The generator makes accumulator-register rotation explicit; there are no
runtime column loops in FixedMul. All code remains standard MCS-51 assembly.
"""
from pathlib import Path

out = []
def emit(*lines): out.extend(lines)
def save():
    for i in range(4): emit(f"mov fx_a+{i},r{7-i}")
    for i in range(4): emit(f"mov fx_b+{i},r{3-i}")
def shift_q():
    # ADD A,Rn shifts the first byte and defines carry, saving a CLR C per bit.
    emit("mov a,r4", "add a,r4", "mov r4,a")
    for r in (5,6,7): emit(f"mov a,r{r}", "rlc a", f"mov r{r},a")
def shift_rem(n):
    for r in range(n): emit(f"mov a,r{r}", "rlc a", f"mov r{r},a")

emit("; Generated by scripts/doom_math_gen.py; do not edit this file by hand.",
     "; Doom 16.16, DW8051 register ABI: a=R4..R7, b=R0..R3, MSB first; result=R4..R7.",
     "; Clobbers A,B,flags,R0..R7 and 15 DATA bytes. Non-reentrant; not ISR-shared.",
     "; MUL returns product bits 16..47 exactly, with low-column carries and signed correction.",
     "; DIV implements Doom's overflow guard and signed truncation toward zero.",
     ".module doom_fixed", "b = 0xF0", "acc = 0xE0", ".globl _DoomFixedMul", ".globl _DoomFixedDiv",
     ".area DSEG (DATA)", "fx_a: .ds 4", "fx_b: .ds 4", "fx_p: .ds 6", "fx_sign: .ds 1", ".area CSEG (CODE)",
     "_DoomFixedMul:")
emit("; Integral operand: seven MULs instead of fifteen.", "mov a,r6", "orl a,r7", "jnz fm_check_b", "ljmp fm_integral", "fm_check_b:",
     "mov a,r2", "orl a,r3", "jnz fm_generic")
for i in range(4): emit(f"mov a,r{i}", f"xch a,r{i+4}", f"mov r{i},a")
emit("ljmp fm_integral", "fm_generic:")
# Keep a in R4..R7, save only b, use R0..R2 as a rotating Comba accumulator.
for i in range(4): emit(f"mov fx_b+{i},r{3-i}")
emit("mov a,r7", "mov b,fx_b", "mul ab", "mov fx_p,a", "mov r0,b", "mov r1,#0", "mov r2,#0")
lo, mid, hi = 0,1,2
for k in range(1,6):
    emit(f"; column {k}: low R{lo}, carry R{mid}/R{hi}; rotate names instead of moving bytes")
    for i in range(4):
        j = k-i
        if not 0 <= j < 4: continue
        emit(f"mov a,r{7-i}", f"mov b,fx_b+{j}", "mul ab", f"add a,r{lo}", f"mov r{lo},a")
        if k < 5: emit("mov a,b", f"addc a,r{mid}", f"mov r{mid},a")
        if k < 4: emit("clr a", f"addc a,r{hi}", f"mov r{hi},a")
    emit(f"mov fx_p+{k},r{lo}")
    if k < 4: emit(f"mov r{lo},#0")
    lo, mid, hi = mid, hi, lo
emit("mov a,r4", "jnb acc.7,fm_a_positive", "clr c", "mov a,fx_p+4", "subb a,fx_b", "mov fx_p+4,a",
     "mov a,fx_p+5", "subb a,fx_b+1", "mov fx_p+5,a", "fm_a_positive:",
     "mov a,fx_b+3", "jnb acc.7,fm_b_positive", "clr c", "mov a,fx_p+4", "subb a,r7", "mov fx_p+4,a",
     "mov a,fx_p+5", "subb a,r6", "mov fx_p+5,a", "fm_b_positive:",
     "mov r7,fx_p+2", "mov r6,fx_p+3", "mov r5,fx_p+4", "mov r4,fx_p+5", "ret", "fm_integral:",
     "mov a,r4", "orl a,r5", "jnz fm_int_nonzero", "mov r4,#0", "mov r5,#0", "mov r6,#0", "mov r7,#0", "ret", "fm_int_nonzero:")
for i in range(4): emit(f"mov fx_b+{i},r{3-i}")
emit("mov a,r5", "mov b,fx_b", "mul ab", "mov fx_p,a", "mov r0,b", "mov r1,#0", "mov r2,#0")
lo, mid, hi = 0,1,2
for k in range(1,4):
    for i in range(2):
        j = k-i
        if not 0 <= j < 4: continue
        emit(f"mov a,r{5-i}", f"mov b,fx_b+{j}", "mul ab", f"add a,r{lo}", f"mov r{lo},a")
        if k < 3: emit("mov a,b", f"addc a,r{mid}", f"mov r{mid},a")
        if k < 2: emit("clr a", f"addc a,r{hi}", f"mov r{hi},a")
    emit(f"mov fx_p+{k},r{lo}")
    if k < 2: emit(f"mov r{lo},#0")
    lo, mid, hi = mid, hi, lo
emit("mov a,r4", "jnb acc.7,fm_int_positive", "clr c", "mov a,fx_p+2", "subb a,fx_b", "mov fx_p+2,a",
     "mov a,fx_p+3", "subb a,fx_b+1", "mov fx_p+3,a", "fm_int_positive:",
     "mov r7,fx_p", "mov r6,fx_p+1", "mov r5,fx_p+2", "mov r4,fx_p+3", "ret", "_DoomFixedDiv:")
save()
emit("mov a,fx_a+3", "xrl a,fx_b+3", "mov fx_sign,a")
for s in ("a","b"):
    emit(f"mov a,fx_{s}+3", f"jnb acc.7,fd_{s}_positive", "clr c")
    for i in range(4): emit("clr a", f"subb a,fx_{s}+{i}", f"mov fx_{s}+{i},a")
    emit(f"fd_{s}_positive:")
emit("; Exact Doom overflow guard, including INT_MIN and a zero divisor.")
for i in range(2):
    emit(f"mov a,fx_a+{i+1}", "rl a", "rl a", "anl a,#3", f"mov fx_p+{i},a", f"mov a,fx_a+{i+2}",
         "rl a", "rl a", "anl a,#0xFC", f"orl a,fx_p+{i}", f"mov fx_p+{i},a")
emit("mov a,fx_a+3", "rl a", "rl a", "anl a,#3", "mov fx_p+2,a", "clr c")
for i in range(4): emit(f"mov a,fx_p+{i}" if i < 3 else "clr a", f"subb a,fx_b+{i}")
emit("jc fd_divide", "mov a,fx_sign", "jb acc.7,fd_min", "mov r4,#0x7F", "mov r5,#0xFF", "mov r6,#0xFF", "mov r7,#0xFF", "ret",
     "fd_min:", "mov r4,#0x80", "mov r5,#0", "mov r6,#0", "mov r7,#0", "ret", "fd_divide:",
     "; Skip known-zero quotient bytes: 16, 24 or 32 bit steps.", "clr c")
for i in range(4): emit(f"mov a,fx_a+{i}", f"subb a,fx_b+{i}")
emit("jc fd_start16", "clr c")
for i in range(4): emit(f"mov a,fx_a+{i+1}" if i < 3 else "clr a", f"subb a,fx_b+{i}")
emit("jc fd_start24", "mov r0,fx_a+2", "mov r1,fx_a+3", "mov r2,#0", "mov r3,#0", "mov r4,#0", "mov r5,#0",
     "mov r6,fx_a", "mov r7,fx_a+1", "mov fx_p+3,#32", "sjmp fd_dispatch", "fd_start24:",
     "mov r0,fx_a+1", "mov r1,fx_a+2", "mov r2,fx_a+3", "mov r3,#0", "mov r4,#0", "mov r5,#0", "mov r6,#0", "mov r7,fx_a",
     "mov fx_p+3,#24", "sjmp fd_dispatch", "fd_start16:")
for i in range(4): emit(f"mov r{i},fx_a+{i}")
for i in range(4,8): emit(f"mov r{i},#0")
emit("mov fx_p+3,#16", "fd_dispatch:", "mov a,fx_b+2", "orl a,fx_b+3", "jz fd_small", "ljmp fd32_loop", "fd_small:",
     "mov a,fx_b+1", "jz fd8_init", "ljmp fd16_init", "fd8_init:", "mov r1,fx_b", "mov r2,fx_p+3",
     "; A zero initial remainder permits one quotient byte in a five-cycle DIV AB.",
     "mov a,r0", "jnz fd8_loop", "mov a,r7", "mov b,r1", "div ab", "mov r0,b",
     "xch a,r4", "xch a,r5", "xch a,r6", "xch a,r7", "mov a,r2", "add a,#0xF8", "mov r2,a", "fd8_loop:")
shift_q(); shift_rem(1)
emit("jc fd8_wrap", "subb a,r1", "jc fd8_next", "sjmp fd8_store", "fd8_wrap:", "clr c", "subb a,r1", "fd8_store:",
     "mov r0,a", "inc r4", "fd8_next:", "djnz r2,fd8_loop", "ljmp fd_finish", "fd16_init:", "mov r2,fx_b", "mov r3,fx_b+1", "fd16_loop:")
shift_q(); shift_rem(2)
emit("jc fd16_wrap", "mov a,r0", "subb a,r2", "mov b,a", "mov a,r1", "subb a,r3", "jc fd16_next",
     "mov r1,a", "mov r0,b", "inc r4", "sjmp fd16_next", "fd16_wrap:", "clr c", "mov a,r0", "subb a,r2", "mov r0,a",
     "mov a,r1", "subb a,r3", "mov r1,a", "inc r4", "fd16_next:", "djnz fx_p+3,fd16_loop", "ljmp fd_finish", "fd32_loop:")
shift_q(); shift_rem(4)
emit("; Signed magnitudes <= 0x80000000: shifted remainder cannot overflow 32 bits.")
for i in range(4): emit(f"mov a,r{i}", f"subb a,fx_b+{i}")
emit("jc fd32_next", "clr c")
for i in range(4): emit(f"mov a,r{i}", f"subb a,fx_b+{i}", f"mov r{i},a")
emit("inc r4", "fd32_next:", "djnz fx_p+3,fd32_loop", "fd_finish:", "mov a,fx_sign", "jnb acc.7,fd_positive", "clr c")
for r in range(4,8): emit("clr a", f"subb a,r{r}", f"mov r{r},a")
emit("fd_positive:", "mov a,r4", "mov r0,a", "mov a,r5", "mov r1,a", "mov a,r7", "mov r4,a", "mov a,r6", "mov r5,a",
     "mov a,r1", "mov r6,a", "mov a,r0", "mov r7,a", "ret", "")

if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "fw/doom/fixed_math.asm"
    target.parent.mkdir(exist_ok=True)
    target.write_text("\n".join(out))
    print(target)

#!/usr/bin/env python3
"""DW8051 direct-bus MPAGE loops: no DPTR switching for each output byte."""
from pathlib import Path
out=[]
def emit(s):out.extend(s.strip().splitlines())

emit('''; Generated by scripts/doom_video_gen.py.
; SDCC ABI 0, little endian, bank zero; DW8051 mem_addr bus with MPAGE.
.module doom_video
.include "doom_cache_config.inc"
.globl _DoomCopy16, _DoomTranspose16, _DoomWrite16, _DoomRead16, _DoomExpand16
.globl _DoomFillChunk, _DoomShadeChunk, _DoomShadeRun
.globl _doom_column_target, _doom_column_frac, _doom_column_step, _doom_column_count
.globl __XPAGE
__XPAGE = DOOM_SFR_MPAGE
mpage = DOOM_SFR_MPAGE
acc = 0xe0
b = 0xf0
.area CSEG (CODE)''')

def start(name):emit(f'_{name}:\npush mpage')
def finish():emit('pop mpage\nret')

start('DoomCopy16')
emit('mov r0,dpl\nmov mpage,dph\nmov dpl,b\nmov dph,a')
for _ in range(16):emit('movx a,@r0\ninc r0\nmovx @dptr,a\ninc dptr')
finish()

start('DoomTranspose16')
emit('mov r0,dpl\nmov mpage,dph\nmov dpl,b\nmov dph,a')
for _ in range(16):emit('''movx a,@r0
inc r0
movx @dptr,a
mov a,dpl
add a,#DOOM_DDR_BURST_BYTES
mov dpl,a
clr a
addc a,dph
mov dph,a''')
finish()

start('DoomWrite16')
emit('mov r0,dpl\nmov mpage,dph\nmov dptr,#(DOOM_MCU_DC_WRITE_BASE + 8)')
for i in range(16):
    if i==8:emit('mov dpl,#(DOOM_MCU_DC_WRITE_BASE & 0xff)')
    emit('movx a,@r0\ninc r0\nmovx @dptr,a\ninc dptr')
finish()

start('DoomRead16')
emit('mov r0,#((DOOM_MCU_DC_READ_BASE + 8) & 0xff)\nmov mpage,#(DOOM_MCU_DC_READ_BASE >> 8)')
for i in range(16):
    if i==8:emit('mov r0,#(DOOM_MCU_DC_READ_BASE & 0xff)')
    emit('movx a,@r0\ninc r0\nmovx @dptr,a\ninc dptr')
finish()

start('DoomExpand16')
emit('''mov r0,dpl
mov b,dph
mov r7,#DOOM_DDR_BURST_BYTES
mov dptr,#DOOM_CACHE_BURST_BASE
expand_pixel:
mov mpage,b
movx a,@r0
inc r0
mov r1,a''')
for page in range(3):emit(f'''mov mpage,#((DOOM_CACHE_PALETTE_BASE >> 8) + {page})
movx a,@r1
movx @dptr,a
inc dptr''')
emit('djnz r7,expand_pixel')
finish()

emit('''_DoomFillChunk:
mov r7,a
mov a,b
fill_pixel:
movx @dptr,a
inc dptr
djnz r7,fill_pixel
ret''')

emit('_DoomShadeChunk:')
emit('''mov dptr,#_doom_column_target
movx a,@dptr
mov r0,a
inc dptr
movx a,@dptr
mov r1,a
mov dptr,#_doom_column_frac
movx a,@dptr
mov r6,a
inc dptr
movx a,@dptr
mov r7,a
mov dptr,#_doom_column_step
movx a,@dptr
mov r4,a
inc dptr
movx a,@dptr
mov r5,a
mov dptr,#_doom_column_count
movx a,@dptr
mov r2,a
mov dpl,r0
mov dph,r1
_DoomShadeRun:
push mpage
shade_pixel:
mov a,r7
rr a
anl a,#0x7f
orl a,#(DOOM_TEXTURE_COLUMN_BASE & 0xff)
mov r0,a
mov mpage,#(DOOM_TEXTURE_COLUMN_BASE >> 8)
movx a,@r0
mov r0,a
mov mpage,#(DOOM_COLORMAP_BASE >> 8)
movx a,@r0
movx @dptr,a
inc dptr
mov a,r6
add a,r4
mov r6,a
mov a,r7
addc a,r5
mov r7,a
djnz r2,shade_pixel
mov dpl,r6
mov dph,r7''')
finish()

if __name__=='__main__':
    (Path(__file__).resolve().parents[1]/'fw/doom/video.asm').write_text('\n'.join(out)+'\n')
